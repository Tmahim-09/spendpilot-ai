  // ─────────────────────────────────────────────────────────────────────────────
  // Test A: Non-Invented User Requirements
  // ─────────────────────────────────────────────────────────────────────────────
  test("Test A: Non-invented user requirements - AI suggested baselines are separated from user requirements", () => {
    const rawDecomp = {
      summary: "Plan gaming PC setup under $3000",
      isPrebuiltVsCustom: "prebuilt",
      items: [
        {
          name: "Gaming Desktop PC",
          productCategory: "desktop",
          searchQuery: "gaming desktop PC RTX 4070",
          fallbackQuery: "gaming desktop",
          allocationPercentage: 55,
          allocatedAmount: 1650,
          requirements: ["32GB RAM", "1TB SSD", "RTX 4070"], // Generated by LLM
          priority: "high",
          diversityGroup: "pc",
        },
        {
          name: "Gaming Monitor",
          productCategory: "monitor",
          searchQuery: "1440p 144Hz gaming monitor",
          fallbackQuery: "gaming monitor",
          allocationPercentage: 15,
          allocatedAmount: 450,
          requirements: ["1440p resolution", "144Hz refresh rate"], // Generated by LLM
          priority: "high",
          diversityGroup: "monitor",
        },
      ],
    };

    // User only asked "Plan gaming PC setup under $3000" - did NOT specify 32GB RAM or 1440p!
    const originalQuery = "Plan gaming PC setup under $3000";
    const result = normalizeDecomposition(rawDecomp, 3000, "USD", originalQuery);

    assert.equal(result.items.length, 2);

    const pcReq = result.items[0];
    assert.ok(pcReq.baselineRequirements, "Must provide baselineRequirements array");
    assert.ok(pcReq.userRequirements, "Must provide userRequirements array");
    // "32GB RAM" was not in original query: must be in baseline, NOT userRequirements!
    assert.equal(pcReq.userRequirements.length, 0, "Must not invent 32GB RAM as an explicit user requirement");
    assert.ok(pcReq.baselineRequirements.includes("32GB RAM"));

    const monitorReq = result.items[1];
    assert.equal(monitorReq.userRequirements?.length, 0, "Must not invent 1440p as an explicit user requirement");
    assert.ok(monitorReq.baselineRequirements?.includes("1440p resolution"));
  });

