function createTestProduct(
  partial: Partial<NormalizedProduct> & { sourceProductId: string; title: string; priceMinor: number }
): NormalizedProduct {
  return {
    source: "channel3",
    brand: null,
    description: null,
    imageUrl: null,
    currency: "USD",
    retailerName: "Verified Retailer",
    retailerUrl: "https://example.com",
    availability: "in_stock",
    specifications: {},
    sourceFacts: [],
    ...partial,
  };
}

function createTestRequirement(
  partial: Partial<SetupRequirementItem> & { id: string; name: string; allocatedAmount: number }
): SetupRequirementItem {
  return {
    searchQuery: partial.name,
    allocationPercentage: 10,
    allocatedAmountMinor: Math.round(partial.allocatedAmount * 100),
    priority: "medium",
    requirements: [],
    ...partial,
  };
}

function createTestBundleItem(
  partial: Partial<RecommendedBundleItem> & {
    requirementId: string;
    requirementName: string;
    allocatedAmountMinor: number;
    selectedProductId: string;
    selectedProduct: NormalizedProduct;
  }
): RecommendedBundleItem {
  return {
    comparison: {
      requirementId: partial.requirementId,
      requirementName: partial.requirementName,
      candidateProductIds: [partial.selectedProductId],
      recommendedProductId: partial.selectedProductId,
      alternativeProductId: null,
      recommendedReason: "Best fit",
      keyDifferences: [],
      tradeoffs: [],
      missingSpecs: [],
    },
    isOverCategoryBudget: (partial.selectedProduct.priceMinor ?? 0) > partial.allocatedAmountMinor,
    ...partial,
  };
}

