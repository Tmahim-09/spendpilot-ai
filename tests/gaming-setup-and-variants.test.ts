  // ─────────────────────────────────────────────────────────────────────────────
  // Test E: Exact Minor Units Price Model ($1,549.99 = 154999 cents)
  // ─────────────────────────────────────────────────────────────────────────────
  test("Test E: Canonical price model - exact integer minor units throughout ($1,549.99 -> 154999 cents)", () => {
    // 1. Direct conversion
    const minorUnits = parseToMinorUnits(1549.99);
    assert.equal(minorUnits, 154999, "$1,549.99 must convert to exactly 154999 integer cents");

    // 2. Major units formatting
    const majorUnits = minorToMajorUnits(minorUnits);
    assert.equal(majorUnits, 1549.99);

    const formatted = formatMinorUnits(minorUnits, "USD");
    assert.equal(formatted, "$1,549.99");

    // 3. Multi-item subtotal integrity test with real regression scenario ($2,723.78)
    const regressionPrices = [
      154999, // PC: $1,549.99
      39999,  // Monitor: $399.99
      12999,  // Keyboard: $129.99
      11999,  // Mouse: $119.99
      9900,   // Headset: $99.00
      3999,   // Desk Mat: $39.99
      28484,  // Chair: $284.84
      9999,   // Speakers: $99.99
    ];

    const subtotalMinor = regressionPrices.reduce((sum, p) => sum + p, 0);
    assert.equal(subtotalMinor, 272378, "Sum of prices must equal 272378 minor units ($2,723.78)");
    assert.equal(formatMinorUnits(subtotalMinor, "USD"), "$2,723.78");

    // Total budget $3,000.00
    const totalBudgetMinor = 300000;
    const remainingBudgetMinor = totalBudgetMinor - subtotalMinor;
    assert.equal(remainingBudgetMinor, 27622, "Remaining budget must be exactly $276.22 (27622 minor units)");
    assert.equal(formatMinorUnits(remainingBudgetMinor, "USD"), "$276.22");
  });

  // ─────────────────────────────────────────────────────────────────────────────
  // Test F: Variant Configurator 3 Genuine States
  // ─────────────────────────────────────────────────────────────────────────────
  test("Test F: Variant Configurator supports 3 genuine states (variants_found, no_variants_verified, unavailable)", async () => {
    // 1. State 3: Unavailable when product cannot be retrieved
    const unavailableState = await retrieveProductVariants("unknown-invalid-product-id", undefined, "USD");
    assert.equal(unavailableState.status, "unavailable");
    assert.equal(unavailableState.options.length, 0);

    // 2. Status property is strongly typed and populated
    assert.ok(["variants_found", "no_variants_verified", "unavailable"].includes(unavailableState.status));
  });

  // ─────────────────────────────────────────────────────────────────────────────
  // Test G: Bundle Subtotal Recalculation on Variant Switch / Product Selection
  // ─────────────────────────────────────────────────────────────────────────────
  test("Test G: Subtotal immediately recalculates on variant switch or alternative selection", () => {
    const requirements: SetupRequirementItem[] = [
      createTestRequirement({ id: "req-1", name: "PC", allocatedAmount: 2400 }),
      createTestRequirement({ id: "req-2", name: "Monitor", allocatedAmount: 600 }),
    ];

    const prodA1 = createTestProduct({ sourceProductId: "pc-base", title: "PC Base 16GB", priceMinor: 150000 });
    const prodA2 = createTestProduct({ sourceProductId: "pc-upgraded", title: "PC Upgraded 32GB", priceMinor: 175000 });
    const prodB1 = createTestProduct({ sourceProductId: "mon-1", title: "1080p Monitor", priceMinor: 20000 });

    const categories: SetupCategorySearchResult[] = [
      { requirementId: "req-1", requirementName: "PC", searchQuery: "pc", allocatedAmountMinor: 240000, products: [prodA1, prodA2], status: "fulfilled" },
      { requirementId: "req-2", requirementName: "Monitor", searchQuery: "mon", allocatedAmountMinor: 60000, products: [prodB1], status: "partial" },
    ];

    const initialBundle = calculateRecommendedBundle({
      totalBudget: 3000,
      currency: "USD",
      requirements,
      categories,
      comparisons: [],
      selectedItemIds: { "req-1": "pc-base" },
    });

    // Initial subtotal: 150000 + 20000 = 170000 ($1,700.00)
    assert.equal(initialBundle.productSubtotalMinor, 170000);
    assert.equal(initialBundle.remainingBudgetMinor, 130000);

    // Switch PC option to upgraded variant:
    const updatedBundle = calculateRecommendedBundle({
      totalBudget: 3000,
      currency: "USD",
      requirements,
      categories,
      comparisons: [],
      selectedItemIds: { "req-1": "pc-upgraded" },
    });

    // Updated subtotal: 175000 + 20000 = 195000 ($1,950.00)
    assert.equal(updatedBundle.productSubtotalMinor, 195000, "Subtotal must recalculate immediately to 195000 cents");
    assert.equal(updatedBundle.remainingBudgetMinor, 105000, "Remaining budget must update immediately to 105000 cents");
  });

  // ─────────────────────────────────────────────────────────────────────────────
  // Test H: Distinct Alternatives Preservation
  // ─────────────────────────────────────────────────────────────────────────────
  test("Test H: Alternative selection in bundle picks genuinely different product models", () => {
    const req = createTestRequirement({
      id: "req-headset",
      name: "Gaming Headset",
      allocatedAmount: 150,
    });

    const mmx1 = createTestProduct({
      sourceProductId: "mmx-100-amzn",
      title: "Beyerdynamic MMX 100 Closed Back Gaming Headset",
      brand: "Beyerdynamic",
      priceMinor: 9900,
    });

    const hyperX = createTestProduct({
      sourceProductId: "hyperx-cloud-2",
      title: "HyperX Cloud II Gaming Headset",
      brand: "HyperX",
      priceMinor: 9999,
    });

    const categories: SetupCategorySearchResult[] = [
      {
        requirementId: "req-headset",
        requirementName: "Gaming Headset",
        searchQuery: "gaming headset",
        allocatedAmountMinor: 15000,
        products: [mmx1, hyperX],
        status: "fulfilled",
      },
    ];

    const bundle = calculateRecommendedBundle({
      totalBudget: 150,
      currency: "USD",
      requirements: [req],
      categories,
      comparisons: [],
    });

    assert.equal(bundle.items.length, 1);
    assert.equal(bundle.items[0].selectedProduct.sourceProductId, "mmx-100-amzn");
    assert.ok(bundle.items[0].alternativeProduct, "Must select an alternative");
    assert.equal(bundle.items[0].alternativeProduct?.sourceProductId, "hyperx-cloud-2");
    assert.notEqual(
      bundle.items[0].alternativeProduct?.title,
      bundle.items[0].selectedProduct.title,
      "Alternative cannot be duplicate of selected product"
    );
  });
